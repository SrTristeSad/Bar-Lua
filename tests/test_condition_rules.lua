package.path='./?.lua;./?/init.lua;'..package.path
local rules=require('src.condition_rules')
local view=require('src.condition_view')
local report=dofile('reports/condition_flow.lua')
assert(report.phase==35 and report.verified_instructions==233 and report.checkpoints==37)
assert(report.tables==7 and report.predicates_resolved==false)
assert(rules.all_pass({},function() return false end)==true)
assert(rules.all_pass({2,4},function(x) return x%2==0 end)==true)
assert(rules.all_pass({2,3,4},function(x) return x%2==0 end)==false)
assert(rules.all_pass(nil,function()return true end)==nil)
local src={1,2,3,4}
local filtered=rules.filter_targets(src,function(x) return x%2==0 end)
assert(table.concat(filtered.items,',')=='4,2') -- swap com ultimo, nao filtro estavel
assert(table.concat(src,',')=='1,2,3,4') -- sem mutar o vetor do chamador
assert(filtered.removed==2 and filtered.remaining==2 and filtered.nonempty)
local empty=rules.filter_targets({},function()return false end)
assert(empty and empty.remaining==0 and empty.nonempty==false)
local chain=rules.apply_chain({1,2,3,4,5},{function(v)return v>1 end,function(v)return v%2==0 end})
assert(chain.remaining==2 and #chain.steps==2 and chain.final_target==nil and chain.damage_applied==false)
local noNext=rules.apply_chain({1},{function()return false end,function()error('filtro indevido')end})
assert(noNext.remaining==0 and #noNext.steps==1)
assert(rules.apply_chain({}, {}) .remaining == 0)
assert(rules.apply_chain({1},'bad')==nil)
local cut=rules.limit_count({11,22,33,44},2,false)
assert(cut and cut.remaining==2 and cut.items[1]==11 and cut.items[2]==22 and cut.limited)
assert(rules.limit_count({11,22,33},3,true).remaining==3)
assert(rules.limit_count({11,22,33},10,false).remaining==3)
assert(rules.limit_count({11,22},0,true).remaining==0)
local value,err=rules.limit_count({11,22,33},2,true)
assert(value==nil and err:find('aleatoria'))
assert(rules.limit_count({1,2},-1,false)==nil)
assert(rules.limit_count({1,2},0.5,false)==nil)
view.reset()
local snap=view.snapshot(report)
assert(snap and snap.index==1 and snap.remaining=='4, 2')
assert(view.keypressed('right'))
assert(view.snapshot(report).index==2)
assert(view.keypressed('left'))
assert(view.snapshot(report).index==1)
for _=1,6 do view.keypressed('right') end
local random=view.snapshot(report)
assert(random.error and random.error:find('aleatoria'))
view.reset()
assert(view.snapshot({phase=34})==nil)
local msgs={}
view.draw(report,{x=0,y=0,w=700,h=570,small={},put=function(text)msgs[#msgs+1]=text end,background=function()end})
assert(#msgs>=8)
print('F35 CONDITIONS LUA OK')
