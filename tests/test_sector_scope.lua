package.path='./?.lua;./?/init.lua;'..package.path
local M=require('src.sector_scope')
local V=require('src.sector_scope_view')
local r=dofile('reports/sector_scope.lua')
assert(r.phase==33 and r.sector_records==84 and r.scope3_count==18)
assert(M.radius(76,100,true)==76)
assert(math.abs(M.radius(76,70,true)-53.2)<1e-10)
assert(M.radius(76,100,false)==nil)
assert(M.radius(-1,100,true)==nil)
assert(M.radius(76,0,true)==0)
assert(M.radius(0/0,100,true)==nil)
assert(M.queryAABB(0,0,0,0,0,20,0)==nil)
local b=M.queryAABB(200,150,0,0,0,76,100)
assert(math.abs(b.minx-1.24)<1e-9 and math.abs(b.maxx-2.76)<1e-9)
assert(math.abs(b.miny-0.74)<1e-9 and math.abs(b.maxy-2.26)<1e-9)
local moved=M.queryAABB(0,0,90,0,50,10,100)
assert(math.abs(moved.cx)<1e-8 and math.abs(moved.cy-50)<1e-8)
V.reset()
local snap=V.snapshot(r)
assert(snap and snap.radius==76 and snap.sectors==84)
assert(V.keypressed('right'));assert(V.snapshot(r).radius==77)
assert(V.keypressed('up'));assert(V.snapshot(r).angle==15)
assert(V.keypressed('r'));assert(V.snapshot(r).radius==76)
local calls={}
V.draw(r,{x=0,y=0,w=650,h=650,small={},background=function(...)end,put=function(t) calls[#calls+1]=t end})
assert(#calls>6)
assert(V.snapshot({phase=32})==nil)
