package.path = './?.lua;./?/init.lua;'..package.path
local M = require('src.hero_hurt')
local function result(h,d,id) return assert(M.simulate_alive(h,d,id)) end
local a=result(120,45,42)
assert(a.hp_after==75 and a.accounted_damage==45)
assert(a.lethal_branch==false and a.recorded_attacker_key==nil)
local b=result(120,120,42)
assert(b.hp_after==0 and b.accounted_damage==120)
assert(b.lethal_branch and b.recorded_attacker_key==42)
local c=result(120,999,42)
assert(c.hp_after==0 and c.accounted_damage==120)
assert(c.virtual_callback_branch and not c.native_events_executed)
local d=result(120,0)
assert(d.hp_after==120 and d.accounted_damage==0 and not d.lethal_branch)
assert(M.simulate_alive(0,30)==nil)
assert(M.simulate_alive(-4,30)==nil)
assert(M.simulate_alive(30,-1)==nil)
assert(M.simulate_alive(30,1.5)==nil)
assert(M.simulate_alive(3.5,1)==nil)
assert(M.simulate_alive(math.huge,5)==nil)
assert(M.simulate_alive(5,math.huge)==nil)
assert(M.simulate_alive(3,4,2.5)==nil)
assert(M.simulate_alive(3,4,1/0)==nil)
local view=require('src.hero_hurt_view')
assert(view.keypressed('up') and view.keypressed('left') and view.keypressed('r'))
assert(not view.keypressed('space'))
local lines={}
local data=dofile('reports/entity_damage_flow.lua')
view.draw(data,{x=0,y=0,w=900,h=700,small={},background=function()end,put=function(line)lines[#lines+1]=line end})
assert(table.concat(lines,' '):find('HP restante',1,true))
assert(table.concat(lines,' '):find('Não modifica',1,true))
print('F25 HERO HURT LUA OK')
