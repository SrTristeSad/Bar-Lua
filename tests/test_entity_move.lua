package.path = './?.lua;./?/init.lua;' .. package.path
local model = require('src.entity_move')
local report = require('reports.entity_move')
assert(report.instructions==59 and report.patterns==21)
local state={x=4,y=-2,flags=0,body_type=2,angle=1.25}
local t=model.plan(state,3,-6)
assert(t.kind=='set_transform' and math.abs(t.x-4.1)<1e-9)
assert(math.abs(t.y+2.2)<1e-9 and t.angle==1.25)
assert(state.x==4 and state.y==-2, 'entrada não pode ser mutada')
assert(model.plan(state,0,0).kind=='none')
assert(model.plan(state,0.00009,0).kind=='none')
assert(model.plan(state,-0.00009,0).kind=='none')
assert(model.plan(state,0,0.0001).kind=='set_transform')
assert(model.plan(state,-0.0001,0).kind=='set_transform')
local velocity=model.plan({x=4,y=-2,flags=32,body_type=2},1,0)
assert(velocity.kind=='write_velocity' and velocity.flags==34 and velocity.clear_timer)
assert(velocity.x==4 and velocity.y==-2)
local awake=model.plan({x=4,y=-2,flags=34,body_type=2},1,0)
assert(awake.kind=='write_velocity' and awake.flags==34 and not awake.clear_timer)
local rest=model.plan({x=4,y=-2,flags=32,body_type=2},0,0)
assert(rest.kind=='write_velocity' and rest.flags==32 and not rest.clear_timer)
assert(model.plan({x=4,y=-2,flags=32,body_type=0},1,0).kind=='none')
assert(model.plan({x=4,y=-2,flags=0,body_type=0},1,0).kind=='set_transform')
local ok=pcall(model.plan,state,0/0,1)
assert(not ok)
print('entity move tests OK')
