local rules=require('src.skill_condition_gate')
local view=require('src.skill_condition_gate_view')
local report=require('reports.skill_condition_gate')
assert(report.phase==38 and report.gameplay_enabled==false)
local nil_list=assert(rules.evaluate(nil,function()error('not called')end))
assert(nil_list.accepted and nil_list.visited==0)
local empty=assert(rules.evaluate({},function()error('not called')end))
assert(empty.accepted and empty.visited==0)
local count=0
local fail=assert(rules.evaluate({1,2,3},function(id) count=count+1;return id~=2 end))
assert(not fail.accepted and fail.visited==2 and fail.failed_id==2 and count==2)
local count2=0
local chain=assert(rules.evaluate_both({1,2},{3},function(id)count2=count2+1;return id~=2 end))
assert(not chain.accepted and chain.target==nil and count2==2 and chain.phase=='creator')
assert(rules.target_noarg()==true)
assert(rules.evaluate('no',function()end)==nil)
assert(rules.evaluate({1},function()return nil end)==nil)
view.reset()
local state=assert(view.snapshot(report))
assert(state.index==1 and state.total==8 and state.accepted)
view.keypressed('right')
assert(view.snapshot(report).index==2)
view.keypressed('r')
assert(view.snapshot(report).index==1)
assert(view.snapshot({phase=38,gameplay_enabled=true})==nil)
local drawn={}
view.draw(report,{x=0,y=0,w=640,h=600,small=nil,background=function()end,put=function(msg)drawn[#drawn+1]=msg end})
assert(#drawn>9)
print('F38 SKILL GATES LUA OK')
