local f=require('src.concrete_conditions')
local view=require('src.concrete_conditions_view')
local function eq(actual,expected,label)
    assert(actual==expected,(label or '?')..' esperado '..tostring(expected)..' obteve '..tostring(actual))
end
-- Camp: oito casos de jump table, invertidos por ContainType.
eq(f.camp(1,3,2,2),true,'same camp')
eq(f.camp(1,3,2,1),false,'other camp')
eq(f.camp(2,3,2,1),true,'different camps')
eq(f.camp(2,3,1,1),false,'same when different required')
for kind=3,8 do
    eq(f.camp(kind,3,kind-3,99),true,'camp enum '..kind)
    eq(f.camp(kind,4,kind-3,99),false,'negation '..kind)
    eq(f.camp(kind,4,99,99),true,'negation mismatch '..kind)
end
eq(f.camp(1,4,1,nil),false,'missing origin')
eq(f.camp(1,4,nil,1),false,'missing candidate')
eq(f.camp(9,3,1,1),false,'unknown camp enum')
-- Entity type exact comparisons + null behavior.
eq(f.entity_kind(3,4,4),true,'same type')
eq(f.entity_kind(3,1,4),false,'different type')
eq(f.entity_kind(4,4,4),false,'invert same type')
eq(f.entity_kind(4,1,4),true,'invert different type')
eq(f.entity_kind(4,nil,4),false,'no entity')
-- Buff absent: GetEntity NULL always false, missing StateDetails depends on contain 2.
eq(f.buff_state(1,false,1),false,'no entity')
eq(f.buff_state(2,true,nil),true,'no state flag negative')
eq(f.buff_state(1,true,nil),false,'no state flag positive')
eq(f.buff_state(1,true,1),true,'active flag')
eq(f.buff_state(1,true,0),false,'inactive flag')
eq(f.buff_state(2,true,0),true,'inactive inverted')
eq(f.buff_state(2,true,1),false,'active inverted')
eq(f.buff_state(2,true,2),true,'byte flag XOR')
local bad,err=f.buff_state(2,true,-1)
eq(bad,nil,'bad flag rejected')
assert(err)
local report={phase=36,functions=6,checkpoints=31}
view.reset()
local state=view.snapshot(report)
assert(state and state.index==1 and state.result==true)
view.keypressed('right')
eq(view.snapshot(report).index,2,'next')
view.keypressed('left')
eq(view.snapshot(report).index,1,'previous')
view.keypressed('r')
eq(view.snapshot(report).index,1,'reset')
assert(view.snapshot({phase=35})==nil)
print('F36 CONCRETE CONDITIONS LUA OK')
