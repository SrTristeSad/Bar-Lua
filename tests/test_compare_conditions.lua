local p=require('src.compare_conditions')
local v=require('src.compare_conditions_view')
local function eq(a,b,desc)assert(a==b,(desc or '?')..' expected '..tostring(b)..' got '..tostring(a))end
-- Entity condition: modes 1/3, contain==3, fallback without mode match.
eq(p.skill_entity(1,3,11,11),true)
eq(p.skill_entity(1,3,11,12),false)
eq(p.skill_entity(1,4,11,11),false)
eq(p.skill_entity(1,4,11,12),true)
eq(p.skill_entity(3,3,10,10),true)
eq(p.skill_entity(3,4,10,11),true)
eq(p.skill_entity(4,3),true)
eq(p.skill_entity(4,4),false)
local bad,err=p.skill_entity(1,3,nil,5);eq(bad,nil);assert(err)
-- Six compare branches, epsilon exactly from ELF.
local eps=0.00009999999747378752
eq(p.compare(5,5,3,eps),true)
eq(p.compare(5,5+eps*0.5,3,eps),true)
eq(p.compare(5,5+eps*2,3,eps),false)
eq(p.compare(5,5+eps*2,4,eps),true)
eq(p.compare(6,5,5,eps),true)
eq(p.compare(5,5,6,eps),true)
eq(p.compare(4,5,7,eps),true)
eq(p.compare(5,5,8,eps),true)
eq(p.compare(5,5,5,eps),false)
eq(p.compare(5,5,7,eps),false)
eq(p.compare(5,5,4,eps),false)
eq(p.compare(-1,5,8,eps),false)
eq(p.compare(5,-1,8,eps),false)
eq(p.compare(5,5,22,eps),false)
-- Four percentage operations and unknown no-op.
eq(p.operate(10,0,200),12)
eq(p.operate(10,1,200),8)
eq(p.operate(10,2,50),5)
eq(p.operate(10,3,50),20)
eq(p.operate(10,9,50),10)
local div;div,err=p.operate(3,3,0);eq(div,nil);assert(err)
eq(p.compare(10,12,6,eps,{code=0,parameter=200}),true)
eq(p.compare(10,6,6,eps,{code=2,parameter=50},{code=1,parameter=100}),true)
local report={phase=37,functions=8,checkpoints=52,epsilon=eps}
v.reset();local snap=v.snapshot(report)
assert(snap and snap.index==1 and snap.result==true)
v.keypressed('right');eq(v.snapshot(report).index,2)
v.keypressed('left');eq(v.snapshot(report).index,1)
v.keypressed('r');eq(v.snapshot(report).index,1)
eq(v.snapshot({phase=36}),nil)
print('F37 COMPARE CONDITIONS LUA OK')
