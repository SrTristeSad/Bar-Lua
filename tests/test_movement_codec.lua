package.path='./?.lua;./?/init.lua;'..package.path
local c=require('src.movement_codec')
local function near(a,b,t) assert(math.abs(a-b)<(t or 1e-8),tostring(a)..' ~= '..tostring(b)) end
assert(c.quantize_degrees(-1)==-1)
assert(c.quantize_degrees(0)==89)
assert(c.quantize_degrees(1)==1)
assert(c.quantize_degrees(90)==23)
assert(c.quantize_degrees(180)==44)
assert(c.quantize_degrees(315)==79)
assert(c.quantize_degrees(359)==90)
assert(c.quantize_degrees(-5)==-2)
assert(c.radians_to_degrees_int(math.pi/2)==90)
assert(c.radians_to_degrees_int(-math.pi/2)==270)
local code,angle=c.scene_direction(1,0,0,0,true,0)
assert(code==79 and angle==315)
code,angle=c.scene_direction(1,0,0,1,false,0)
assert(code==34 and angle==135)
code,angle=c.scene_direction(1,1,1,1,true,0)
assert(code==-1 and angle==-1)
code,angle=c.scene_direction(0,0,0,0,false,math.pi)
assert(code==44 and angle==180)
code,angle=c.scene_direction(0,0,0,0,false,-math.pi/2)
assert(code==68 and angle==270)
local x,y=c.move_vector(100,0,0,90,true,false)
near(x,0);near(y,1)
x,y=c.move_vector(200,100,0,90,true,true)
near(x,1);near(y,2)
x,y=c.move_vector(200,100,0,90,false,true)
near(x,1);near(y,0)
x,y=c.move_vector(200,100,0,90,false,false)
near(x,0);near(y,0)
assert(c.changed_direction(44,44)==false)
local changed,new=c.changed_direction(44,45)
assert(changed and new==45)
local msg=c.message_fields(20,23)
assert(msg.sequence==22 and msg.direction==23 and msg.visual_degrees==92)
local bad=pcall(c.quantize_degrees,0/0)
assert(not bad)
print('movement codec tests OK')