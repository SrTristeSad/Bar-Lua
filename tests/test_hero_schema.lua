package.path='./?.lua;./?/init.lua;'..package.path
local schema=require('src.hero_schema')
local view=require('src.level_attributes_view')
local catalog=dofile('cache/hero_levels.lua')
local native=dofile('reports/hero_schema.lua')
assert(native.phase==30 and native.total_instructions==586)
assert(schema.validatedHpTypes(native))
local current=assert(schema.valueType(native,5))
local reference=assert(schema.valueType(native,11))
assert(current.offset=='0x314' and reference.offset=='0x310')
assert(schema.valueType(native,4).kind=='delegate_entity')
assert(schema.valueType(native,33).kind=='hero_field')
assert(schema.valueType(native,34)==nil)
assert(schema.valueType({},5)==nil)
assert(schema.slotLabel('0x44')=='HP inicial')
assert(schema.slotLabel('0x38')=='atributo nao identificado')
local barbarian
for _,group in ipairs(catalog.groups) do if group.base_id==210001 then barbarian=group;break end end
assert(barbarian and #barbarian.levels>=3)
assert(schema.configHp(barbarian.levels[1])==240)
assert(schema.configHp(barbarian.levels[2])==240)
assert(schema.configHp({values={['0x44']=-1}})==nil)
assert(schema.configHp({values={['0x44']=1.5}})==nil)
local buffer={}
local pane={x=0,y=0,w=960,h=640,small='fakefont',background=function()end,
    put=function(s) buffer[#buffer+1]=tostring(s) end}
view.keypressed('r')
view.draw(barbarian,{total_instructions=696},pane,native)
local s=table.concat(buffer,'\n')
assert(s:find('HP inicial',1,true))
assert(s:find('240',1,true))
assert(s:find('ValueType 5',1,true))
assert(s:find('0x38',1,true))
assert(view.keypressed('t'))
buffer={};view.draw(barbarian,{},pane,native);s=table.concat(buffer,'\n')
assert(s:find('Dispatch',1,true))
assert(s:find('HP atual',1,true))
assert(view.keypressed('right'))
buffer={};view.draw(barbarian,{},pane,native);s=table.concat(buffer,'\n')
assert(s:find('pagina 2/3',1,true))
assert(view.keypressed('r'))
assert(view.showTypes==false and view.typePage==1 and view.level==1)
print('F30 HERO SCHEMA LUA OK')
